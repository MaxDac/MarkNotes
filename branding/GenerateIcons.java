import java.awt.BasicStroke;
import java.awt.Color;
import java.awt.RenderingHints;
import java.awt.Shape;
import java.awt.geom.AffineTransform;
import java.awt.geom.Area;
import java.awt.geom.Path2D;
import java.awt.geom.PathIterator;
import java.awt.geom.Rectangle2D;
import java.awt.geom.RoundRectangle2D;
import java.awt.image.BufferedImage;
import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import javax.imageio.ImageIO;
import javax.xml.parsers.DocumentBuilderFactory;
import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.Node;

/**
 * Generates the MarkNotes icon assets from the master SVGs in this folder. Needs only a JDK (11+):
 *
 * <pre>java branding/GenerateIcons.java</pre>
 *
 * (run from the repository root). It supports the small SVG subset the masters use: {@code rect} (with
 * {@code rx}), {@code path} with absolute M/H/V/L/Z commands, solid fills and strokes (width, join, cap) and
 * a luminance {@code mask} made of such shapes. Strokes and masks are flattened into plain filled outlines,
 * so the Android vector drawables need no masks or strokes.
 *
 * Outputs:
 * - branding/png/marknotes-icon-512.png (Play Store icon) and marknotes-icon-1024.png;
 * - Android adaptive icon: drawable/ic_launcher_foreground.xml (content scaled into the 66dp safe zone),
 *   drawable/ic_launcher_monochrome.xml, values/ic_launcher_background.xml and the mipmap-anydpi-v26 icons;
 * - drawable/marknotes_mark.xml, the in-app logo.
 */
public class GenerateIcons {
    private static final Path BRANDING = Path.of("branding");
    private static final Path RES = Path.of("app", "src", "main", "res");
    private static final String GENERATED =
        "<!-- Generated by branding/GenerateIcons.java from branding/%s. Do not edit by hand. -->\n";

    /** Adaptive icons are 108dp; content must fit the centred 66dp circle (kept 2dp inside it). */
    private static final double ADAPTIVE_SIZE = 108;
    private static final double SAFE_RADIUS = 31;

    record Fill(Area area, Color color) {}

    record Svg(Rectangle2D viewBox, List<Fill> fills, Fill background) {}

    public static void main(String[] args) throws Exception {
        Svg icon = load("marknotes-icon.svg");
        Svg mark = load("marknotes-mark.svg");
        Svg mono = load("marknotes-monochrome.svg");

        Path png = BRANDING.resolve("png");
        Files.createDirectories(png);
        for (int size : new int[] {512, 1024}) {
            writePng(icon, size, png.resolve("marknotes-icon-" + size + ".png"));
        }

        // Scale the icon content (everything but the background tile) into the adaptive icon safe zone.
        Rectangle2D content = bounds(icon.fills());
        double half = Math.hypot(content.getWidth(), content.getHeight()) / 2;
        double scale = SAFE_RADIUS / half;
        AffineTransform adaptive = new AffineTransform();
        adaptive.translate(ADAPTIVE_SIZE / 2, ADAPTIVE_SIZE / 2);
        adaptive.scale(scale, scale);
        adaptive.translate(-content.getCenterX(), -content.getCenterY());

        Path drawable = RES.resolve("drawable");
        Files.createDirectories(drawable);
        writeVector(drawable.resolve("ic_launcher_foreground.xml"), "marknotes-icon.svg", icon.fills(), adaptive,
            ADAPTIVE_SIZE, ADAPTIVE_SIZE, 108);
        writeVector(drawable.resolve("ic_launcher_monochrome.xml"), "marknotes-monochrome.svg", mono.fills(),
            adaptive, ADAPTIVE_SIZE, ADAPTIVE_SIZE, 108);

        Rectangle2D box = mark.viewBox();
        AffineTransform toViewport = AffineTransform.getTranslateInstance(-box.getX(), -box.getY());
        writeVector(drawable.resolve("marknotes_mark.xml"), "marknotes-mark.svg", mark.fills(), toViewport,
            box.getWidth(), box.getHeight(), 48);

        Path values = RES.resolve("values");
        Files.createDirectories(values);
        write(values.resolve("ic_launcher_background.xml"),
            "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n" + GENERATED.formatted("marknotes-icon.svg")
                + "<resources>\n    <color name=\"ic_launcher_background\">" + hex(icon.background().color())
                + "</color>\n</resources>\n");

        Path anydpi = RES.resolve("mipmap-anydpi-v26");
        Files.createDirectories(anydpi);
        String adaptiveXml = "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n" + GENERATED.formatted("marknotes-icon.svg")
            + "<adaptive-icon xmlns:android=\"http://schemas.android.com/apk/res/android\">\n"
            + "    <background android:drawable=\"@color/ic_launcher_background\" />\n"
            + "    <foreground android:drawable=\"@drawable/ic_launcher_foreground\" />\n"
            + "    <monochrome android:drawable=\"@drawable/ic_launcher_monochrome\" />\n"
            + "</adaptive-icon>\n";
        write(anydpi.resolve("ic_launcher.xml"), adaptiveXml);
        write(anydpi.resolve("ic_launcher_round.xml"), adaptiveXml);
        System.out.println("Icons generated.");
    }

    // ---- SVG loading ----

    private static Svg load(String name) throws Exception {
        DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
        Document doc = factory.newDocumentBuilder().parse(BRANDING.resolve(name).toFile());
        Element root = doc.getDocumentElement();
        double[] vb = numbers(root.getAttribute("viewBox"));
        Rectangle2D viewBox = new Rectangle2D.Double(vb[0], vb[1], vb[2], vb[3]);
        List<Fill> fills = new ArrayList<>();
        Fill background = null;
        for (Element el : children(root)) {
            if (el.getTagName().equals("defs")) continue;
            List<Fill> shapes = fills(el);
            String mask = el.getAttribute("mask");
            if (!mask.isEmpty()) {
                Area keep = mask(doc, mask.replaceAll("^url\\(#(.*)\\)$", "$1"));
                shapes.forEach(f -> f.area().intersect(keep));
            }
            if (el.getTagName().equals("rect") && background == null && fills.isEmpty()) {
                background = shapes.get(0);
            } else {
                fills.addAll(shapes);
            }
        }
        return new Svg(viewBox, fills, background);
    }

    /** Area where the luminance mask is white: white shapes add to it, black shapes cut it away. */
    private static Area mask(Document doc, String id) {
        Element maskEl = null;
        for (Node n = doc.getDocumentElement(); n != null; n = next(n)) {
            if (n instanceof Element e && e.getTagName().equals("mask") && e.getAttribute("id").equals(id)) {
                maskEl = e;
                break;
            }
        }
        if (maskEl == null) throw new IllegalArgumentException("Missing mask " + id);
        Area area = new Area();
        for (Element el : children(maskEl)) {
            for (Fill f : fills(el)) {
                float[] hsb = Color.RGBtoHSB(f.color().getRed(), f.color().getGreen(), f.color().getBlue(), null);
                if (hsb[2] >= 0.5f) area.add(f.area()); else area.subtract(f.area());
            }
        }
        return area;
    }

    private static Node next(Node n) {
        if (n.getFirstChild() != null) return n.getFirstChild();
        while (n != null && n.getNextSibling() == null) n = n.getParentNode();
        return n == null ? null : n.getNextSibling();
    }

    /** The filled regions an element paints: its fill and its stroke (merged when the same colour). */
    private static List<Fill> fills(Element el) {
        Shape shape = switch (el.getTagName()) {
            case "rect" -> {
                double w = num(el, "width", 0), h = num(el, "height", 0);
                double rx = num(el, "rx", num(el, "ry", 0)), ry = num(el, "ry", rx);
                yield new RoundRectangle2D.Double(num(el, "x", 0), num(el, "y", 0), w, h, 2 * rx, 2 * ry);
            }
            case "path" -> parsePath(el.getAttribute("d"));
            default -> throw new IllegalArgumentException("Unsupported element " + el.getTagName());
        };
        List<Fill> result = new ArrayList<>();
        Color fill = color(el.hasAttribute("fill") ? el.getAttribute("fill") : "#000");
        if (fill != null) result.add(new Fill(new Area(shape), fill));
        Color stroke = color(el.getAttribute("stroke"));
        if (stroke != null) {
            BasicStroke basic = new BasicStroke(
                (float) num(el, "stroke-width", 1),
                switch (el.getAttribute("stroke-linecap")) {
                    case "round" -> BasicStroke.CAP_ROUND;
                    case "square" -> BasicStroke.CAP_SQUARE;
                    default -> BasicStroke.CAP_BUTT;
                },
                switch (el.getAttribute("stroke-linejoin")) {
                    case "round" -> BasicStroke.JOIN_ROUND;
                    case "bevel" -> BasicStroke.JOIN_BEVEL;
                    default -> BasicStroke.JOIN_MITER;
                },
                4f
            );
            Area outline = new Area(basic.createStrokedShape(shape));
            if (!result.isEmpty() && result.get(0).color().equals(stroke)) {
                result.get(0).area().add(outline);
            } else {
                result.add(new Fill(outline, stroke));
            }
        }
        return result;
    }

    private static final Pattern TOKEN = Pattern.compile("([MHVLZmhvlz])|(-?[0-9]*\\.?[0-9]+)");

    private static Path2D parsePath(String d) {
        Path2D.Double path = new Path2D.Double();
        Matcher m = TOKEN.matcher(d);
        List<String> tokens = new ArrayList<>();
        while (m.find()) tokens.add(m.group());
        double x = 0, y = 0;
        char cmd = 0;
        for (int i = 0; i < tokens.size(); ) {
            String t = tokens.get(i);
            if (Character.isLetter(t.charAt(0))) {
                cmd = t.charAt(0);
                i++;
                if (cmd == 'Z' || cmd == 'z') {
                    path.closePath();
                    continue;
                }
            }
            if (Character.isLowerCase(cmd)) throw new IllegalArgumentException("Relative commands unsupported: " + d);
            switch (cmd) {
                case 'M' -> {
                    x = Double.parseDouble(tokens.get(i++));
                    y = Double.parseDouble(tokens.get(i++));
                    path.moveTo(x, y);
                    cmd = 'L';
                }
                case 'L' -> {
                    x = Double.parseDouble(tokens.get(i++));
                    y = Double.parseDouble(tokens.get(i++));
                    path.lineTo(x, y);
                }
                case 'H' -> {
                    x = Double.parseDouble(tokens.get(i++));
                    path.lineTo(x, y);
                }
                case 'V' -> {
                    y = Double.parseDouble(tokens.get(i++));
                    path.lineTo(x, y);
                }
                default -> throw new IllegalArgumentException("Unsupported path data: " + d);
            }
        }
        return path;
    }

    private static List<Element> children(Element parent) {
        List<Element> list = new ArrayList<>();
        for (Node n = parent.getFirstChild(); n != null; n = n.getNextSibling()) {
            if (n instanceof Element e) list.add(e);
        }
        return list;
    }

    private static double num(Element el, String attr, double fallback) {
        return el.hasAttribute(attr) ? Double.parseDouble(el.getAttribute(attr)) : fallback;
    }

    private static double[] numbers(String s) {
        String[] parts = s.trim().split("[\\s,]+");
        double[] out = new double[parts.length];
        for (int i = 0; i < parts.length; i++) out[i] = Double.parseDouble(parts[i]);
        return out;
    }

    private static Color color(String value) {
        if (value == null || value.isEmpty() || value.equals("none")) return null;
        String hex = value.substring(1);
        if (hex.length() == 3) hex = hex.replaceAll("(.)", "$1$1");
        return new Color(Integer.parseInt(hex, 16));
    }

    private static String hex(Color c) {
        return String.format(Locale.ROOT, "#%02X%02X%02X", c.getRed(), c.getGreen(), c.getBlue());
    }

    private static Rectangle2D bounds(List<Fill> fills) {
        Area all = new Area();
        fills.forEach(f -> all.add(f.area()));
        return all.getBounds2D();
    }

    // ---- Outputs ----

    private static void writePng(Svg svg, int size, Path out) throws IOException {
        BufferedImage image = new BufferedImage(size, size, BufferedImage.TYPE_INT_ARGB);
        var g = image.createGraphics();
        g.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
        g.setRenderingHint(RenderingHints.KEY_RENDERING, RenderingHints.VALUE_RENDER_QUALITY);
        g.setRenderingHint(RenderingHints.KEY_STROKE_CONTROL, RenderingHints.VALUE_STROKE_PURE);
        Rectangle2D box = svg.viewBox();
        g.scale(size / box.getWidth(), size / box.getHeight());
        g.translate(-box.getX(), -box.getY());
        List<Fill> all = new ArrayList<>();
        if (svg.background() != null) all.add(svg.background());
        all.addAll(svg.fills());
        for (Fill f : all) {
            g.setColor(f.color());
            g.fill(f.area());
        }
        g.dispose();
        ImageIO.write(image, "png", out.toFile());
    }

    private static void writeVector(Path out, String source, List<Fill> fills, AffineTransform transform,
                                    double viewportWidth, double viewportHeight, int sizeDp) throws IOException {
        StringBuilder sb = new StringBuilder("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
        sb.append(GENERATED.formatted(source));
        sb.append("<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n");
        sb.append("    android:width=\"").append(sizeDp).append("dp\"\n");
        sb.append("    android:height=\"").append(sizeDp).append("dp\"\n");
        sb.append("    android:viewportWidth=\"").append(fmt(viewportWidth)).append("\"\n");
        sb.append("    android:viewportHeight=\"").append(fmt(viewportHeight)).append("\">\n");
        for (Fill f : fills) {
            if (f.area().isEmpty()) continue;
            PathIterator it = f.area().getPathIterator(transform);
            sb.append("    <path\n");
            sb.append("        android:fillColor=\"").append(hex(f.color())).append("\"\n");
            if (it.getWindingRule() == PathIterator.WIND_EVEN_ODD) {
                sb.append("        android:fillType=\"evenOdd\"\n");
            }
            sb.append("        android:pathData=\"").append(pathData(it)).append("\" />\n");
        }
        sb.append("</vector>\n");
        write(out, sb.toString());
    }

    private static String pathData(PathIterator it) {
        StringBuilder sb = new StringBuilder();
        double[] c = new double[6];
        for (; !it.isDone(); it.next()) {
            switch (it.currentSegment(c)) {
                case PathIterator.SEG_MOVETO -> sb.append('M').append(pts(c, 1));
                case PathIterator.SEG_LINETO -> sb.append('L').append(pts(c, 1));
                case PathIterator.SEG_QUADTO -> sb.append('Q').append(pts(c, 2));
                case PathIterator.SEG_CUBICTO -> sb.append('C').append(pts(c, 3));
                case PathIterator.SEG_CLOSE -> sb.append('Z');
                default -> throw new IllegalStateException();
            }
        }
        return sb.toString();
    }

    private static String pts(double[] c, int count) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < count * 2; i++) {
            if (i > 0) sb.append(i % 2 == 0 ? ' ' : ',');
            sb.append(fmt(c[i]));
        }
        return sb.toString();
    }

    private static String fmt(double v) {
        String s = String.format(Locale.ROOT, "%.2f", v).replaceAll("\\.?0+$", "");
        return s.equals("-0") ? "0" : s;
    }

    private static void write(Path out, String content) throws IOException {
        Files.writeString(out, content, StandardCharsets.UTF_8);
        System.out.println("  wrote " + out);
    }

    private GenerateIcons() {}
}
